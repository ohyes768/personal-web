/** 射线法: 点是否在任一多边形内 */
function pointInPolygon(lng: number, lat: number, polygon: [number, number][]): boolean {
  let inside = false;
  const n = polygon.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

/** 点是否在萧山接壤板块 (闻堰/宁围/盈丰) 任一边界内 (GCJ-02) */
export function isInXiaoshanBorder(lng: number, lat: number): boolean {
  return Object.values(XIAOSHAN_BORDER_BOUNDARIES).some(poly => pointInPolygon(lng, lat, poly));
}

/** 点是否在服务覆盖范围 (滨江 + 萧山接壤板块) 内 —— POI 绘制围栏口径 */
export function isInScope(lng: number, lat: number): boolean {
  return isInBinjiang(lng, lat) || isInXiaoshanBorder(lng, lat);
}

/** 覆盖范围围栏外接框 (默认视野用, 对齐后端 _scope_bounds 口径) */
export function scopeBounds(): { lngMin: number; latMin: number; lngMax: number; latMax: number } {
  const pts = [BINJIANG_BOUNDARY, ...Object.values(XIAOSHAN_BORDER_BOUNDARIES)].flat();
  const lngs = pts.map(p => p[0]);
  const lats = pts.map(p => p[1]);
  return { lngMin: Math.min(...lngs), latMin: Math.min(...lats), lngMax: Math.max(...lngs), latMax: Math.max(...lats) };
}
