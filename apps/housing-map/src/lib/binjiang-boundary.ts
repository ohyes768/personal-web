/** 射线法判断点是否在滨江区边界内 (GCJ-02) */
export function isInBinjiang(lng: number, lat: number): boolean {
  let inside = false;
  const n = BINJIANG_BOUNDARY.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const [xi, yi] = BINJIANG_BOUNDARY[i];
    const [xj, yj] = BINJIANG_BOUNDARY[j];
    if ((yi > lat) !== (yj > lat) && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

